import { cn } from "@/lib/utils";
import { useTranslation } from "react-i18next";

type LogoLayout = "full" | "compact" | "vertical" | "symbol";
type LogoTone = "color" | "reversed" | "navy" | "white";

const FILES: Record<LogoLayout, string> = {
  full: "launchpad-logo",
  compact: "launchpad-logo-compact",
  vertical: "launchpad-logo-vertical",
  symbol: "launchpad-symbol",
};

interface LogoProps {
  layout?: LogoLayout;
  /** color on light surfaces, reversed on navy or the brand gradient. */
  tone?: LogoTone;
  className?: string;
}

/**
 * Launchpad lockups from client/public/brand (generated by scripts/brand/build-logos.mjs).
 * Size it with a height class; the width follows the artwork.
 */
export function Logo({ layout = "compact", tone = "color", className }: LogoProps) {
  const { t } = useTranslation();
  return (
    <img
      src={`/brand/${FILES[layout]}-${tone}.svg`}
      alt={t("brand.name")}
      className={cn("h-8 w-auto select-none", className)}
      draggable={false}
    />
  );
}
